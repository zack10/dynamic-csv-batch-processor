CREATE TABLE replacement_run (
    submission_id VARCHAR(80) PRIMARY KEY,
    fingerprint VARCHAR(64) NOT NULL,
    mode VARCHAR(20) NOT NULL,
    sql_statements BIGINT NOT NULL DEFAULT 0,
    affected_rows BIGINT NOT NULL DEFAULT 0,
    zero_matches BIGINT NOT NULL DEFAULT 0,
    unknown_counts BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE staged_command (
    command_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id VARCHAR(80) NOT NULL,
    source_record BIGINT NOT NULL,
    mapping_index INTEGER NOT NULL,
    mapping_name VARCHAR(80) NOT NULL,
    property_key VARCHAR(63) NOT NULL,
    old_values TEXT NOT NULL,
    new_value VARCHAR(256) NOT NULL,
    UNIQUE (submission_id, source_record, mapping_index),
    FOREIGN KEY (submission_id) REFERENCES replacement_run(submission_id)
);
CREATE INDEX command_export_order ON staged_command(submission_id, command_id);

CREATE TABLE staged_pair (
    submission_id VARCHAR(80) NOT NULL,
    source_record BIGINT NOT NULL,
    mapping_index INTEGER NOT NULL,
    pair_index INTEGER NOT NULL,
    property_key VARCHAR(63) NOT NULL,
    old_value VARCHAR(256) NOT NULL,
    new_value VARCHAR(256) NOT NULL,
    PRIMARY KEY (submission_id, source_record, mapping_index, pair_index),
    FOREIGN KEY (submission_id) REFERENCES replacement_run(submission_id)
);
CREATE INDEX pair_old_lookup ON staged_pair(submission_id, property_key, old_value, new_value);
CREATE INDEX pair_new_lookup ON staged_pair(submission_id, property_key, new_value, old_value);

